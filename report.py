from pathlib import Path

print("[+] H4CK-B0T report generation started...")

files_to_include = [
    "discovery_result.txt",
    "scan_result.txt",
    "validation_result.txt",
    "evidence_result.txt",
    "correlation_result.txt",
    "risk_result.txt"
]

with open("report.txt", "w", encoding="utf-8") as report:

    report.write("H4CK-B0T SECURITY VALIDATION REPORT\n")
    report.write("==================================\n\n")

    report.write("This report combines the results generated by the "
                 "H4CK-B0T security validation pipeline.\n\n")

    for filename in files_to_include:

        report.write("\n")
        report.write("=" * 60 + "\n")
        report.write(f"{filename}\n")
        report.write("=" * 60 + "\n\n")

        if Path(filename).exists():

            with open(filename, "r", encoding="utf-8") as source:
                content = source.read()

            report.write(content)

        else:
            report.write("File not found.\n")


print("[+] Report generation completed")
print("[+] Final report saved to report.txt")